#!/usr/bin/env python3
"""tools/build_gallery.py - inline the merged catalog into gallery/index.html.

A static page opened over file:// cannot fetch() its own data (CORS blocks it), and
requiring a local web server for a browsing aid is a bad trade. So the catalog is
inlined at build time: the gallery is one self-contained file, openable by double-click.

Usage:
    python -m tools.build_gallery
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tools.catalog import merge  # noqa: E402

GALLERY_DIR = ROOT / "gallery"
TEMPLATE = GALLERY_DIR / "index.html"
MARKER_START = "// --- catalog data (generated by tools/build_gallery.py) ---"
MARKER_END = "// --- end catalog data ---"


def json_for_script(obj) -> str:
    """Serialize for inlining inside a <script> block.

    Plain JSON does not escape the forward slash, so a string containing "</script>"
    would close the block and execute as markup. Escaping "</" is the minimal change
    that keeps the payload valid JSON while removing the breakout sequence.
    """
    payload = json.dumps(obj, ensure_ascii=False, separators=(",", ":"))
    return payload.replace("</", "<\\/")


def build() -> Path:
    index = merge()
    payload = json_for_script(index)
    template = TEMPLATE.read_text(encoding="utf-8")

    inline = (
        f"{MARKER_START}\n"
        f"const CATALOG = {payload};\n"
        f"const DATA = Promise.resolve(CATALOG);\n"
        f"{MARKER_END}"
    )

    # Idempotent: if the generated block exists, replace just that block. Otherwise
    # bootstrap it from the fetch() version and inject the block.
    block = re.compile(re.escape(MARKER_START) + r".*?" + re.escape(MARKER_END), re.S)
    if block.search(template):
        out = block.sub(inline, template, count=1)
    else:
        fetch_re = re.compile(r"const DATA = fetch\(.*?\)\.then\(r => r\.json\(\)\);", re.S)
        if not fetch_re.search(template):
            raise RuntimeError("gallery template has neither the generated block nor the fetch loader")
        out = fetch_re.sub(inline, template, count=1)
    TEMPLATE.write_text(out, encoding="utf-8")
    return TEMPLATE


def main() -> int:
    path = build()
    print(f"inlined catalog into {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
